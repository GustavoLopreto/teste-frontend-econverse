const IMAGE_BASE = 'https://cdn.dummyjson.com/product-images'

interface ItemOptions {
  discount?: number
  isNew?: boolean
}

// Imagens do projeto chegam do Vite como caminho absoluto ou data URI.
function isLocalImage(photo: string): boolean {
  return photo.startsWith('/') || photo.startsWith('data:')
}

function item(
  category: string,
  productName: string,
  brand: string,
  price: number,
  photo: string,
  descriptionShort: string,
  options: ItemOptions = {},
): CatalogProduct {
  return {
    productName,
    descriptionShort,
    brand,
    price,
    category,
    slug: slugify(productName),
    photo: isLocalImage(photo) ? photo : `${IMAGE_BASE}/${photo}/thumbnail.webp`,
    ...options,
  }
}

